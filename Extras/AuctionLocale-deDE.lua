-- The Auction House can load before Blasta and cache these labels.
local function refreshAuctionLabels()
    local auction = DUI:GetModule("AuctionHouse")
    local window = auction and auction.ns and auction.ns.Window
    if window and window.TABS then
        local labels = { buy = "Buy", sell = "Sell", auctions = "My auctions" }
        for _, tab in ipairs(window.TABS) do
            local key = labels[tab.id]
            if key then tab.text = DUI.L[key] end
        end
    end
    if BINDING_NAME_DAYLIGHTUI_AH_ACT then
        BINDING_NAME_DAYLIGHTUI_AH_ACT = DUI.L["Auction House: post or cancel the next one"]
    end
end

refreshAuctionLabels()
